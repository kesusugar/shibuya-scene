import {mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {createVehicleVisual} from './vehicle-visual-source.mjs';
import {mergeVertices} from 'three/addons/utils/BufferGeometryUtils.js';
import {BufferGeometry} from 'three';
import {VEHICLES} from '../src/traffic/config.mjs';
const models={};
for(const type of Object.keys(VEHICLES).filter(t=>t!=='scooter')){
 const v=createVehicleVisual();v.update({active:true,type,x:0,y:0,z:0,heading:0,speed:0,steering:0,slot:{}},0);
 v.root.position.set(0,0,0);v.root.traverse(o=>{if(o.isMesh){const old=o.geometry;o.geometry=new BufferGeometry().copy(old);delete o.geometry.parameters;const indexed=mergeVertices(o.geometry,1e-5);o.geometry.dispose();o.geometry=indexed;old.dispose();}});models[type]=v.root.toJSON();v.dispose();
}
// Stable identifiers make rebuilding reviewable and reproducible.
let json=JSON.stringify({version:1,models},(key,value)=>typeof value==='number'?Math.round(value*10000)/10000:value);const ids=new Map();
json=json.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi,id=>{if(!ids.has(id))ids.set(id,`playable-${ids.size}`);return ids.get(id);});
const key=createHash('sha256').update(readFileSync('scripts/vehicle-visual-source.mjs')).update(readFileSync('src/traffic/config.mjs')).digest('hex');
const pack=JSON.parse(json);pack.sourceKey=key;
mkdirSync('src/player/generated',{recursive:true});
writeFileSync('src/player/generated/vehicles.mjs','// Generated by npm run bake:playable.\nexport default JSON.parse('+JSON.stringify(JSON.stringify(pack))+');\n');
console.log(`Prebuilt ${Object.keys(models).length} vehicles: ${Buffer.byteLength(JSON.stringify(pack))} bytes`);
